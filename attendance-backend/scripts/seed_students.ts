const parseStudents = (raw: string, section: string) => {
  return raw
    .trim()
    .split('\n')
    .map((line) => {
      const match = line.match(/^(.*?)\s+(\d+)$/);
      if (!match) return null;
      return {
        name: match[1].trim(),
        rollNo: match[2].trim(),
        section,
      };
    })
    .filter(Boolean);
};

