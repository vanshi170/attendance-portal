async function main() {
  console.log('Seeding students from sections A-E...');
  const allStudents = [
    ...parseStudents(sectionA, 'A'),
    ...parseStudents(sectionB, 'B'),
    ...parseStudents(sectionC, 'C'),
    ...parseStudents(sectionD, 'D'),
    ...parseStudents(sectionE, 'E'),
  ] as any[];

  console.log(`Parsed ${allStudents.length} students.`);

  // Wipe dummy students first
  console.log('Wiping old students...');
  await prisma.attendanceRecord.deleteMany();
  await prisma.studentLecture.deleteMany();
  await prisma.student.deleteMany();

  // Create new students
  console.log('Inserting new students...');
  for (const st of allStudents) {
    await prisma.student.upsert({
      where: { rollNo: st.rollNo },
      update: {
        name: st.name,
        section: st.section,
      },
      create: {
        name: st.name,
        rollNo: st.rollNo,
        section: st.section,
      }
    });
  }

  console.log('Done!');
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
